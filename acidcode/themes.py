DEFAULT = "acid"


def _variables(palette: dict[str, str]) -> dict[str, str]:
    return {
        f"acid-{key.replace('_', '-')}": value for key, value in palette.items()
    }


def _build(name: str, palette: dict[str, str]) -> Theme:
    return Theme(
        name=name,
        primary=palette["accent"],
        secondary=palette["border"],
        warning=palette["accent2"],
        error=palette["error"],
        success=palette["accent"],
        accent=palette["accent2"],
        foreground=palette["text"],
        background=palette["bg"],
        surface=palette["header"],
        panel=palette["panel"],
        dark=True,
        variables=_variables(palette),
    )


THEMES: dict[str, Theme] = {
    name: _build(name, palette) for name, palette in PALETTES.items()
}
